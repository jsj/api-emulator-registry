import assert from 'node:assert/strict';
import { createApp, Store, withServer } from '../../scripts/cli-smoke-runtime.mjs';
import { plugin } from './api-emulator.mjs';
import { FIXTURE_ADDRESS } from './src/store.mjs';
import { FIXTURE_CREDENTIALS } from './src/routes/orders.mjs';

const app = createApp();
plugin.register(app, new Store());
const headers = { POLY_API_KEY: FIXTURE_CREDENTIALS.apiKey, POLY_ADDRESS: FIXTURE_ADDRESS,
  POLY_SIGNATURE: 'fixture-only', POLY_TIMESTAMP: '1780272000', POLY_PASSPHRASE: FIXTURE_CREDENTIALS.passphrase };
await withServer(app, async url => {
  const request = async (path, options = {}) => {
    const res = await fetch(`${url}${path}`, options);
    return { status: res.status, body: await res.json() };
  };
  const json = (method, body, auth = headers) => ({ method, headers: { ...auth, 'content-type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal((await request('/gamma/markets?closed=true')).body.length, 0);
  assert.equal((await request('/gamma/markets?limit=1&offset=1')).body[0].id, 'polymarket-space-launch-2026');
  assert.equal((await request('/gamma/markets/keyset?limit=0')).status, 400);
  assert.equal((await request('/gamma/markets/keyset?after_cursor=bad')).status, 400);
  assert.equal((await request('/gamma/markets/missing')).status, 404);
  assert.equal((await request('/gamma/markets/slug/polymarket-weather-2026')).body.clobTokenIds, '["1001","1002"]');
  assert.equal((await request('/gamma/events')).body.length, 2);
  assert.equal((await request('/gamma/events/event-polymarket-weather-2026')).body.markets.length, 1);
  assert.equal((await request('/gamma/public-search?q=temperature')).body.events.length, 1);
  assert.equal((await request('/gamma/public-search')).status, 400);
  assert.equal((await request('/clob/book?token_id=missing')).status, 404);
  assert.equal((await request('/clob/price?token_id=1001&side=bad')).status, 400);
  assert.equal((await request('/clob/books', json('POST', {}))).status, 400);
  assert.equal((await request('/clob/books', json('POST', [{ token_id: 'missing' }]))).status, 404);
  assert.deepEqual((await request('/clob/midpoints', json('POST', [{ token_id: '1001' }, { token_id: '1002' }]))).body, { 1001: '0.58', 1002: '0.42' });
  assert.deepEqual((await request('/clob/prices', json('POST', [{ token_id: '1001', side: 'BUY' }, { token_id: '1001', side: 'SELL' }]))).body, { 1001: { BUY: '0.57', SELL: '0.59' } });
  assert.equal((await request('/clob/spreads', json('POST', [{ token_id: '1001' }]))).body['1001'], '0.02');
  assert.equal((await request('/clob/last-trades-prices', json('POST', [{ token_id: '1001' }]))).body[0].price, '0.58');
  assert.equal((await request('/clob/fee-rate?token_id=1001')).body.base_fee, 0);
  assert.equal((await request('/clob/prices-history?market=1001')).body.history.length, 2);
  assert.equal((await request('/clob/prices-history?market=1001&startTs=bad')).status, 400);
  assert.equal((await request('/clob/data/orders')).status, 401);
  const payload = { order: { tokenId: '1001', side: 'BUY', makerAmount: '5000000', takerAmount: '10000000' }, orderType: 'GTC' };
  assert.equal((await request('/clob/order', json('POST', payload, {}))).status, 401);
  assert.equal((await request('/clob/order', json('POST', { ...payload, orderType: 'FOK' }))).status, 400);
  assert.equal((await request('/clob/order', json('POST', { ...payload, order: { ...payload.order, makerAmount: '6000000' } }))).status, 400);
  assert.equal((await request('/clob/order', json('POST', { ...payload, order: { ...payload.order, makerAmount: '5010000' } }))).status, 400);
  const placed = await request('/clob/order', json('POST', payload));
  assert.equal(placed.status, 200);
  const id = placed.body.orderID;
  assert.equal((await request('/clob/data/orders', { headers })).body.data.length, 1);
  const other = { ...headers, POLY_ADDRESS: '0x2222222222222222222222222222222222222222' };
  assert.equal((await request('/clob/data/orders', { headers: other })).body.data.length, 0);
  assert.equal((await request(`/clob/data/order/${id}`, { headers: other })).status, 404);
  assert.equal((await request('/clob/order', json('DELETE', { orderID: id }, other))).body.canceled.length, 0);
  assert.deepEqual((await request('/clob/orders', json('DELETE', [id]))).body.canceled, [id]);
  assert.equal((await request('/clob/data/orders', { headers })).body.data.length, 0);
  assert.equal((await request('/clob/order', json('DELETE', { orderID: id }))).body.canceled.length, 0);
  assert.equal((await request('/clob/data/trades', { headers })).body.data.length, 0);
  assert.equal((await request('/data/v2/positions?user=bad')).status, 400);
  assert.equal((await request(`/data/v2/positions?user=${FIXTURE_ADDRESS}&status=CLOSED`)).body.data.length, 0);
  assert.equal((await request(`/data/v2/positions?user=${other.POLY_ADDRESS}`)).body.data.length, 0);
  assert.equal((await request(`/data/positions?user=${FIXTURE_ADDRESS}`)).body[0].size, 10);
  assert.equal((await request(`/data/value?user=${FIXTURE_ADDRESS}`)).body[0].value, 5.8);
});
console.log('polymarket HTTP regression smoke ok');
